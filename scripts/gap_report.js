// Report the image gap: which of the 1,056 HN records still have no stored
// image, and which hosts those records link to. This is a planning tool for
// further acquisition; it does not fetch anything.
const fs = require('fs');
const path = require('path');

const ROOT = 'D:/news';
function readJson(p) {
  let raw = fs.readFileSync(p, 'utf8');
  if (raw.charCodeAt(0) === 0xFEFF) raw = raw.slice(1);
  return JSON.parse(raw);
}

const records = readJson(path.join(ROOT, 'site', 'data', 'records.json'));
const arr = Array.isArray(records) ? records : (records.records || Object.values(records));
const hnUrls = readJson(path.join(ROOT, 'scripts', 'hn_urls.json'));
const images = readJson(path.join(ROOT, 'site', 'data', 'images.json'));

function hostOf(u) {
  try { return new URL(u).hostname.replace(/^www\./, ''); } catch (e) { return '(invalid)'; }
}
function prov(u) {
  if (/oregonnews\.uoregon\.edu/.test(u)) return 'oregon';
  if (/paperspast\.natlib\.govt\.nz/.test(u)) return 'paperspast';
  if (/loc\.gov/.test(u)) return 'loc';
  if (/newspapers\.library\.in\.gov/.test(u)) return 'indiana';
  if (/gateway\.okhistory\.org/.test(u)) return 'oklahoma';
  if (/texashistory\.unt\.edu/.test(u)) return 'texas';
  if (/historicnewspapers\.sc\.edu/.test(u)) return 'southcarolina';
  if (/gahistoricnewspapers/.test(u)) return 'georgia';
  if (/theguardian\.com/.test(u)) return 'guardian';
  if (/washingtonpost\.com/.test(u)) return 'washingtonpost';
  if (/latimes\.com/.test(u)) return 'latimes';
  if (/newspaperarchive\.com/.test(u)) return 'newspaperarchive';
  if (/rarenewspapers\.com/.test(u)) return 'rarenewspapers';
  if (/britishnewspaperarchive|bl\.uk/.test(u)) return 'british';
  return 'other';
}

const withImages = new Set(Object.keys(images));
const missing = arr.filter(r => !withImages.has(r.hn_id));

const hostCounts = {};
const provCounts = {};
const noUrl = [];
for (const r of missing) {
  const urls = hnUrls[r.hn_id] || [];
  if (!urls.length) { noUrl.push(r.hn_id); continue; }
  const hosts = new Set(urls.map(hostOf));
  const provs = new Set(urls.map(prov));
  for (const h of hosts) hostCounts[h] = (hostCounts[h] || 0) + 1;
  for (const p of provs) provCounts[p] = (provCounts[p] || 0) + 1;
}

const lines = [];
lines.push('# Image gap report');
lines.push('');
lines.push('Generated by `scripts/gap_report.js`. Counts are records, not URLs.');
lines.push('');
lines.push('- Total records: **' + arr.length + '**');
lines.push('- Records with at least one stored image: **' + withImages.size + '**');
lines.push('- Records still without an image: **' + missing.length + '**');
lines.push('  - of which have no source URL at all: **' + noUrl.length + '**');
lines.push('  - of which have at least one source URL: **' + (missing.length - noUrl.length) + '**');
lines.push('');
lines.push('## Missing records by provider class');
lines.push('');
for (const [p, n] of Object.entries(provCounts).sort((a, b) => b[1] - a[1])) {
  lines.push('| ' + p + ' | ' + n + ' |');
}
lines.push('');
lines.push('## Missing records by host (top 60)');
lines.push('');
lines.push('| Host | Records |');
lines.push('|---|---:|');
for (const [h, n] of Object.entries(hostCounts).sort((a, b) => b[1] - a[1]).slice(0, 60)) {
  lines.push('| ' + h + ' | ' + n + ' |');
}
lines.push('');
lines.push('## Records with no source URL');
lines.push('');
lines.push(noUrl.join(', '));
lines.push('');

fs.writeFileSync(path.join(ROOT, 'docs', 'IMAGE_GAP_REPORT.md'), lines.join('\n'));

// CSV of every missing record that still has a URL, for manual/automated work.
const rows = [['hn_id', 'heading', 'date', 'urls']];
for (const r of missing) {
  const urls = hnUrls[r.hn_id] || [];
  if (!urls.length) continue;
  rows.push([r.hn_id, r.heading || '', r.date || '', urls.join(' | ')]);
}
const csv = rows.map(row => row.map(v => '"' + String(v).replace(/"/g, '""') + '"').join(',')).join('\r\n');
fs.writeFileSync(path.join(ROOT, 'docs', 'IMAGE_GAP_REPORT.csv'), csv);

console.log('Missing records: ' + missing.length + '  (no URL: ' + noUrl.length + ')');
console.log('Top hosts:');
for (const [h, n] of Object.entries(hostCounts).sort((a, b) => b[1] - a[1]).slice(0, 25)) {
  console.log('  ' + String(n).padStart(4) + '  ' + h);
}
console.log('\nWrote docs/IMAGE_GAP_REPORT.md and .csv');
